-- HU-21. Preguntas frecuentes del chatbot.
--
-- El chatbot no usa inteligencia artificial: busca coincidencias de palabras en esta
-- tabla. El contenido lo edita un administrador desde la API, sin desplegar código, y
-- por eso vive en la base y no en el programa.
--
-- No hay borrado: una pregunta se desactiva. Así una edición equivocada se deshace.
-- palabras_clave va en minúsculas, sin tildes y separada por comas.
--
-- Esta tabla no se relaciona con ninguna de envíos ni de cuentas, a propósito: el
-- chatbot no debe poder consultar datos de nadie.

create table chatbot_faq (
    id bigint generated by default as identity,
    intencion varchar(60) not null unique,
    categoria varchar(40) not null,
    pregunta varchar(200) not null,
    palabras_clave varchar(500) not null,
    respuesta varchar(1000) not null,
    activo boolean not null default true,
    orden integer not null default 0,
    updated_at timestamp(6) with time zone not null,
    updated_by varchar(50),

    constraint pk_chatbot_faq primary key (id),
    constraint ck_chatbot_faq_orden check (orden between 0 and 999)
);

create index idx_chatbot_faq_activo on chatbot_faq (activo, orden);
