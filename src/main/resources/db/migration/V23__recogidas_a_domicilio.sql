-- HU-20. Recogidas a domicilio.
--
-- Una recogida es una visita programada para recoger un paquete en la dirección del
-- remitente. Es una tabla aparte de shipments porque no todas las recogidas tienen
-- envío: se puede pedir la recogida antes de registrar el paquete, y luego vincularlo.
-- Cuando sí hay envío, se relaciona por tracking_number, el mismo criterio que ya
-- usan las tablas de los otros módulos.
--
-- La dirección y el contacto son datos privados: solo se muestran al operador
-- asignado a la recogida (ver consulted en la aplicación), así que no hay vista
-- pública de esta tabla.
--
-- pickup_events es la bitácora: cada cambio de la recogida deja una fila, con el
-- estado anterior y el nuevo. Es lo que permite responder "qué le pasó a esta
-- recogida" y por qué está en el estado en que está.
--
-- No hay llaves foráneas hacia shipments ni hacia auth_users: la correlación con el
-- envío es por tracking_number y la auditoría no debe romperse si un usuario se
-- desactiva o se renombra.

create table pickups (
    id bigint generated by default as identity,
    pickup_number varchar(255) not null unique,

    status varchar(255) not null,
    address varchar(255) not null,
    city_id bigint not null,
    contact_name varchar(255) not null,
    contact_phone varchar(255) not null,
    scheduled_date date not null,
    time_slot varchar(255) not null,
    package_size varchar(255) not null,
    weight_kg numeric(8,2) not null,

    shipment_tracking_number varchar(255),
    assigned_username varchar(50),
    requested_by varchar(50) not null,
    requested_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,

    constraint pk_pickups primary key (id),
    constraint fk_pickups_city foreign key (city_id) references cities (id),
    constraint ck_pickups_weight check (weight_kg > 0)
);

create index idx_pickups_status on pickups (status);
create index idx_pickups_assigned on pickups (assigned_username);
create index idx_pickups_shipment on pickups (shipment_tracking_number);

create table pickup_events (
    id bigint generated by default as identity,
    pickup_number varchar(255) not null,
    event_id varchar(255) not null unique,
    type varchar(255) not null,
    previous_status varchar(255),
    new_status varchar(255),
    detail varchar(500),
    actor_username varchar(50) not null,
    occurred_at timestamp(6) with time zone not null,

    constraint pk_pickup_events primary key (id)
);

create index idx_pickup_events_number on pickup_events (pickup_number, occurred_at);

-- Persistir el evento junto con la recogida permite reintentar su entrega al broker.
create table pickup_outbox (
    pickup_number varchar(255) primary key,
    tracking_number varchar(255) not null,
    city_id bigint not null,
    picked_up_at timestamp(6) with time zone not null,
    occurred_at timestamp(6) with time zone not null,
    published_at timestamp(6) with time zone
);
