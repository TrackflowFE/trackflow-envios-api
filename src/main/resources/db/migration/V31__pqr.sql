-- HU-19. Peticiones, quejas y reclamos (PQR).
--
-- Una PQR la radica el remitente o el destinatario de un envío, sin cuenta: el
-- radicado, junto con el correo registrado, es su credencial para consultarla.
--
-- El texto de la descripción y de la respuesta se guarda tal como llegó. No se
-- escapa aquí: escapar al guardar mezcla dos problemas y deja datos alterados. Lo que
-- evita que un texto malicioso se ejecute es que la API lo entrega siempre como JSON y
-- que el navegador lo pinta como texto.
--
-- numero_seguimiento no tiene llave foránea hacia shipments, igual que en recogidas:
-- radicar una PQR no debe servir para averiguar qué envíos existen.
--
-- pqr_eventos es la bitácora: cada cambio deja una fila con quién lo hizo y cuándo.

create sequence pqr_radicado_seq start with 1 increment by 1;

create table pqr (
    id bigint generated by default as identity,
    radicado varchar(20) not null unique,

    tipo varchar(20) not null,
    estado varchar(20) not null,
    descripcion varchar(2000) not null,

    contacto_nombre varchar(120) not null,
    contacto_email varchar(120) not null,
    contacto_telefono varchar(20),
    numero_seguimiento varchar(14),
    acepta_tratamiento_datos boolean not null,

    respuesta varchar(2000),
    respondido_por varchar(50),

    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,

    constraint pk_pqr primary key (id),
    constraint ck_pqr_tipo check (tipo in ('PETICION', 'QUEJA', 'RECLAMO')),
    constraint ck_pqr_estado check (estado in ('RECIBIDA', 'EN_TRAMITE', 'RESUELTA', 'CERRADA')),
    constraint ck_pqr_datos check (acepta_tratamiento_datos)
);

create index idx_pqr_estado on pqr (estado, created_at);

create table pqr_eventos (
    id bigint generated by default as identity,
    radicado varchar(20) not null,
    estado_anterior varchar(20),
    estado_nuevo varchar(20) not null,
    detalle varchar(500),
    actor varchar(50) not null,
    occurred_at timestamp(6) with time zone not null,

    constraint pk_pqr_eventos primary key (id)
);

create index idx_pqr_eventos_radicado on pqr_eventos (radicado, occurred_at);
