-- HU-11. Gestión de usuarios, roles y permisos.
--
-- Hasta ahora los usuarios solo se creaban al arrancar, desde variables de entorno.
-- Para administrarlos desde la API hacen falta dos cosas que el esquema no tenía:
-- poder bloquear una cuenta por intentos fallidos y dejar constancia de quién
-- cambió qué.

-- Intentos fallidos seguidos; vuelve a cero con cada inicio de sesión correcto.
alter table auth_users add column failed_attempts integer not null default 0;
-- Mientras tenga fecha futura, el usuario no puede entrar aunque acierte la clave.
-- La quita el administrador al desbloquear, o el propio vencimiento.
alter table auth_users add column locked_until timestamp(6) with time zone;

-- Quién hizo qué y cuándo sobre usuarios, roles y permisos. Es un registro de solo
-- escritura: no se edita ni se borra, porque su valor está en que nadie lo toque.
create table auth_audit (
    id bigint generated by default as identity,
    -- Quien ejecuta la acción. 'sistema' cuando la hace el arranque, no una persona.
    actor varchar(50) not null,
    accion varchar(40) not null,
    -- Sobre quién o sobre qué recae: normalmente el usuario afectado.
    objetivo varchar(100),
    -- Qué cambió, en texto legible. Nunca contraseñas ni hashes.
    detalle varchar(500),
    ocurrido_en timestamp(6) with time zone not null,
    primary key (id)
);

-- Las consultas de auditoría son siempre por fecha, de lo más reciente hacia atrás.
create index idx_auth_audit_ocurrido_en on auth_audit (ocurrido_en desc);
